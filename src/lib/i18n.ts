/**
 * Translation System
 * 
 * This module contains all user-facing text translations for the ARIA HUB application.
 * It supports three languages: English (en), Persian/Dari (fa), and Pashto (ps).
 * 
 * STRUCTURE:
 * The translations object is organized as a nested Record structure:
 * - First level: language code ('en', 'fa', 'ps')
 * - Second level: translation key → translation value
 * 
 * Example:
 * translations = {
 *   en: { 'admin.nav.dashboard': 'Dashboard' },
 *   fa: { 'admin.nav.dashboard': 'داشبورد' },
 *   ps: { 'admin.nav.dashboard': 'ډشبورډ' }
 * }
 * 
 * NAMING CONVENTIONS:
 * Translation keys follow a hierarchical dot-notation pattern:
 * 
 * - admin.*           → Admin panel elements (admin.nav.dashboard, admin.button.save)
 * - common.*          → Shared UI elements (common.save, common.cancel, common.delete)
 * - form.*            → Form field labels (form.title, form.description)
 * - status.*          → Status messages (status.loading, status.success)
 * - error.*           → Error messages (error.required, error.invalid)
 * - placeholder.*     → Input placeholders (placeholder.search, placeholder.enterEmail)
 * - [section].*       → Frontend sections (nav.*, hero.*, services.*, visas.*, etc.)
 * 
 * PARAMETRIC TRANSLATIONS:
 * Some translations contain placeholders for dynamic values using curly braces:
 * 
 * Example:
 * 'admin.table.showing': 'Showing {count} of {total}'
 * 
 * When used with parameters: translate('en', 'admin.table.showing', { count: 5, total: 20 })
 * Result: 'Showing 5 of 20'
 * 
 * FALLBACK BEHAVIOR:
 * If a translation key is missing in the requested language, the system automatically
 * falls back to English. If English is also missing, the key itself is returned.
 * This ensures the UI never shows undefined/null values.
 * 
 * COMPLETENESS REQUIREMENT:
 * Every translation key that exists in 'en' MUST also exist in 'fa' and 'ps' with
 * appropriate translated values to maintain feature parity across languages.
 */
